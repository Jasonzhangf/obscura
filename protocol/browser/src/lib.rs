    #[test]
    fn control_token_round_trips_and_rejects_missing_or_empty_values() {
        let control = control("019d0d66-c5dc-7492-a097-39ac8f06f434");
        let encoded = serde_json::to_value(&control).unwrap();
        assert_eq!(encoded["token"], "019d0d66-c5dc-7492-a097-39ac8f06f434");
        assert_eq!(serde_json::from_value::<Control>(encoded).unwrap(), control);

        let missing = serde_json::json!({
            "epoch": 7,
            "phase": {"type": "human", "attachment_id": 11}
        });
        assert!(serde_json::from_value::<Control>(missing).is_err());

        let empty = serde_json::json!({
            "epoch": 7,
            "token": "",
            "phase": {"type": "human", "attachment_id": 11}
        });
        assert!(serde_json::from_value::<Control>(empty).is_err());
    }

    #[test]
    fn session_status_abi_requires_the_control_token() {
        let status = status("host-token");
        let encoded = serde_json::to_value(&status).unwrap();
        assert_eq!(encoded["control"]["token"], "host-token");
        assert_eq!(encoded["remote_focus"]["focused"], true);
        assert_eq!(encoded["remote_focus"]["editable"], true);
        assert_eq!(serde_json::from_value::<SessionStatus>(encoded.clone()).unwrap(), status);

        let mut missing = encoded.clone();
        missing["control"].as_object_mut().unwrap().remove("token");
        assert!(serde_json::from_value::<SessionStatus>(missing).is_err());

        let mut empty = encoded;
        empty["control"]["token"] = serde_json::json!("");
        assert!(serde_json::from_value::<SessionStatus>(empty).is_err());
    }

    #[test]
    fn remote_focus_capability_round_trips_and_rejects_unknown_fields() {
        let capability = RemoteFocusCapability {
            session_id: "session".into(),
            document_revision: 8,
            viewport_revision: 5,
            control_epoch: 7,
            focused: true,
            editable: false,
        };
        let encoded = serde_json::to_value(&capability).unwrap();
        assert_eq!(serde_json::from_value::<RemoteFocusCapability>(encoded.clone()).unwrap(), capability);
        let mut unknown = encoded;
        unknown["unexpected"] = serde_json::json!(true);
        assert!(serde_json::from_value::<RemoteFocusCapability>(unknown).is_err());

        let mut status = serde_json::to_value(status("host-token")).unwrap();
        status["remote_focus"] = serde_json::Value::Null;
        assert_eq!(serde_json::from_value::<SessionStatus>(status).unwrap().remote_focus, None);
    }

    #[test]
    fn encoded_source_dimensions_keep_raw_and_padded_sizes_typed() {
        assert_eq!(SourceDimensions::from_raw(347, 580), SourceDimensions { width: 348, height: 580 });
        assert_eq!(SourceDimensions::from_raw(348, 580), SourceDimensions { width: 348, height: 580 });
        let encoded = serde_json::to_value(SourceDimensions::from_raw(347, 580)).unwrap();
        assert_eq!(encoded, serde_json::json!({"width":348,"height":580}));
    }

